  function renderStatus() {
    const s = state.status;
    if (!s) { setSvc('ollama', false, 'Serveur injoignable'); setSvc('images', false, 'Serveur injoignable'); return; }
    const inst = s.installed || {};
    const loaded = (s.ollama.loaded || []).length;
    setSvc('ollama', s.ollama.online, s.ollama.online ? `${s.ollama.models.length} modèle(s) · ${loaded ? 'chargé en mémoire' : 'déchargé'}`
      : inst.ollama ? 'Arrêté' : 'Non installé (ollama.com)');
    setSvc('images', !!inst.images, (s.images || {}).busy ? 'Génération en cours' : inst.images ? 'Prêt (chargé à la demande)' : 'Modèles manquants : voir Guide');
    const b = $('start-ollama');
    b.hidden = s.ollama.online || !inst.ollama;
    b.disabled = !!state.starting.ollama;
    b.textContent = state.starting.ollama ? 'Démarrage...' : 'Démarrer';
    // Le moteur d'images est lancé à la demande par le serveur : le bouton ne dépend que de l'installation.
    $('btn-genall').disabled = !inst.images;
    $('images-banner').hidden = !!inst.images;
    const has = !!s.improve_model;
    for (const [box, label, key, what] of [
      ['v-improve', 'opt-improve', 'studio.improve', 'chaque description avant de dessiner'],
      ['chat-improve', 'opt-improve-chat', 'studio.improve.chat', 'votre demande avant la conception et le code']]) {
      const imp = $(box);
      if (imp.dataset.init === undefined) {
        imp.dataset.init = '1';
        try { imp.checked = localStorage.getItem(key) === '1'; } catch { /* stockage indisponible */ }
      }
      imp.disabled = !has;
      $(label).className = 'opt' + (has ? '' : ' off');
      $(label).title = has ? `Réécrit ${what} avec ${s.improve_model}` : 'Modèle gnokit/improve-prompt non installé dans Ollama';
    }
    fillModels($('model'), 'studio.model', s.ollama.models, false);
    fillModels($('model-design'), 'studio.model.design', s.ollama.models, true);
  }

  // Remplit une liste de modèles en conservant le choix courant ou mémorisé.
  function fillModels(sel, key, models, allowNone) {
    const sig = models.join('|');
    if (sel.dataset.sig === sig) return;
    let saved = null; try { saved = localStorage.getItem(key); } catch { /* stockage indisponible */ }
    const prev = sel.dataset.sig === undefined ? saved : sel.value;
    const opts = models.map((m) => el('option', { value: m, text: m }));
    if (allowNone) opts.unshift(el('option', { value: '', text: 'Aucune (coder directement)' }));
    sel.replaceChildren(...opts);
    sel.dataset.sig = sig;
    // Conception : désactivée par défaut (un appel Ollama de plus, lent sans GPU). Code : préfère un modèle « coder ».
    const fallback = allowNone ? '' : (models.find((m) => /coder|code/i.test(m)) || models[0]);
    const pick = [prev, fallback].find((v) => v != null && (v === '' ? allowNone : models.includes(v)));
    sel.value = pick == null ? '' : pick;
  }

  async function startService(id) {
    state.starting[id] = true; renderStatus();
    try {
      const r = await api(`/api/services/${id}/start`, { method: 'POST' });
      toast(r.message);
      for (let i = 0; i < 20; i++) {
        await new Promise((res) => setTimeout(res, 5000));
        await refreshStatus();
        if (state.status && state.status[id].online) break;
      }
    } catch (e) { toast(e.message); }
    state.starting[id] = false; renderStatus();
  }

  async function refreshStatus() {
    try { state.status = await api('/api/status'); } catch { state.status = null; }
    renderStatus();
    renderProgress();
  }

  // Affiche la progression de sd-cli sur l'image en cours de génération (aucun re-rendu des slots).
  function renderProgress() {
    const slot = state.slots.find((s) => s.busy && s.prog);
    if (!slot) return;
    const p = state.status && state.status.images && state.status.images.progress;
    const bar = slot.prog.firstChild, label = slot.prog.lastChild;
    if (p && p.phase === 'sample' && p.step > 0 && slot.liveStep !== p.step) { slot.liveStep = p.step; loadLive(slot); }
    if (p && p.phase === 'improve') {
      bar.className = 'bar indet';
      label.textContent = `Amélioration du prompt (${state.status.improve_model}) · ${Math.floor(p.elapsed / 60)}:${String(p.elapsed % 60).padStart(2, '0')}`;
      return;
    }
    if (!p) { bar.className = 'bar indet'; label.textContent = 'En attente du moteur d\'images...'; return; }
    const pct = p.steps > 0 ? Math.min(100, Math.round((p.step / p.steps) * 100)) : null;
    const t = `${Math.floor(p.elapsed / 60)}:${String(p.elapsed % 60).padStart(2, '0')}`;
    let text;
    if (p.phase === 'decode') text = 'Décodage de l\'image...';
    else if (p.phase === 'sample') text = `Étape ${p.step}/${p.steps}` + (p.speed ? ` · ${p.speed}` : '') + (p.eta ? ` · reste ${p.eta}` : '');
    else text = 'Chargement des modèles' + (pct != null && p.step > 0 ? ` · ${pct}%` : '...');
    bar.className = 'bar' + (pct == null || p.phase === 'decode' ? ' indet' : '');
    bar.firstChild.style.width = (pct == null || p.phase === 'decode' ? 100 : pct) + '%';
    label.textContent = `${text} · ${t}`;
  }

